#include <windows.h>
#include <tchar.h>
#define  SET_POPUP_MENU_BGND  1

#include "common.h"  //  syslog(), get_system_message()
#include "systray.h"

static NOTIFYICONDATA NotifyIconData;

//  registered message which Explorer broadcasts when it (re)creates the taskbar
static UINT wm_taskbar_created = 0 ;

static HMENU hMenu = NULL ;
//***************************************************************
void load_tray_menu(WORD menuID)
{
   // HMENU hTopMenu = LoadMenu (g_hinst, MAKEINTRESOURCE(menuID)) ;
   HMENU hTopMenu = LoadMenu (GetModuleHandle(NULL), MAKEINTRESOURCE(menuID)) ;
   
   if (hTopMenu == NULL) {
      syslog(_T("LoadMenu: %s\n"), get_system_message()) ;
   } 
   
   hMenu = GetSubMenu(hTopMenu, 0) ;
   if (hMenu == NULL) {
      syslog(_T("GetSubMenu: %s\n"), get_system_message()) ;
   } 
   
#ifdef   SET_POPUP_MENU_BGND
   // https://learn.microsoft.com/en-us/windows/win32/api/winuser/ns-winuser-menuinfo
   // change the menu backcolor:  doesn't work with MinGW32
   MENUINFO mnuInfo = {0};
   mnuInfo.cbSize   = sizeof(mnuInfo);
   mnuInfo.fMask    = MIM_BACKGROUND | MIM_APPLYTOSUBMENUS;
   mnuInfo.hbrBack  = CreateSolidBrush(RGB(128,128,128));
   // if(SetMenuInfo(hTopMenu,&mnuInfo)==FALSE) {
   if(SetMenuInfo(hMenu,&mnuInfo)==FALSE) {
      syslog(_T("Popup Menu background not changed: %s\n"), get_system_message());
   }   
#endif   
}

//***************************************************************
// put the icon into a system tray
//  Call from WM_INITDIALOG
//
//  REQUIRED, along with this call: the window procedure must also call
//  respond_to_taskbar_created(message) for every message, before its main switch.
//  Without that, the icon is lost permanently whenever Explorer restarts,
//  while the program keeps running. See respond_to_taskbar_created() below.
//***************************************************************
//lint -esym(18, _NOTIFYICONDATAA::szTip) // c:\mingw\include\shellapi.h  166  Error 18: Symbol '_NOTIFYICONDATAA::szTip' redeclared (size) 
//lint -esym(18, _NOTIFYICONDATAW::szTip) // c:\mingw\include\shellapi.h  166  Error 18: Symbol '_NOTIFYICONDATAA::szTip' redeclared (size) 
void attach_tray_icon(HWND hwnd, TCHAR const * const szClassName, WORD iconID)
{
   NotifyIconData.cbSize = sizeof (NOTIFYICONDATA);
   NotifyIconData.hWnd = hwnd;
   NotifyIconData.uID = iconID ;
   NotifyIconData.uFlags = NIF_ICON | NIF_TIP | NIF_MESSAGE;
   NotifyIconData.uCallbackMessage = WM_USER; // tray events will generate WM_USER event
   // NotifyIconData.hIcon = (HICON) LoadIcon (g_hinst, MAKEINTRESOURCE (iconID));
   NotifyIconData.hIcon = LoadIcon ((HINSTANCE) GetWindowLong(hwnd, GWL_HINSTANCE), MAKEINTRESOURCE (iconID));
   lstrcpy (NotifyIconData.szTip, szClassName); // max 64 characters
   //  If Explorer restarts, it broadcasts "TaskbarCreated" and all tray icons are lost;
   //  register the message here, so respond_to_taskbar_created() can recognize it.
   wm_taskbar_created = RegisterWindowMessage(_T("TaskbarCreated"));
   //  getting string from STRINGTABLE in .rc file
   // LoadString(hInstance, IDS_APPTOOLTIP,nidApp.szTip,MAX_LOADSTRING);
   Shell_NotifyIcon (NIM_ADD, &NotifyIconData);
}


//**************************************************************************************
//  Handle messages generated by system tray application,
//     typicaly WM_USER or equivalent
//  The type of tray event which generated the message can be found in lParam.
//  
//  However, this code caused a situation where clicking outside the 
//  title bar did *not* make the menu go away.
//  Microsoft's solutions to this problem are documented in
//  http://support.microsoft.com/kb/q135788/
//  and are implemented below.
//**************************************************************************************
BOOL respond_to_tray_clicks(HWND hwnd, LPARAM lParam)
{
   POINT MouseCoordinates;
   switch (lParam)   {
   case WM_LBUTTONUP:
   case WM_RBUTTONUP:
      // display a tray menu
      SetForegroundWindow(hwnd); //  MSoft fix1 for stuck title bar
      GetCursorPos(&MouseCoordinates);
      TrackPopupMenu(hMenu, TPM_LEFTALIGN | TPM_LEFTBUTTON | TPM_BOTTOMALIGN,
         MouseCoordinates.x, MouseCoordinates.y, 0, hwnd, NULL);
      PostMessage(hwnd, WM_NULL, 0, 0); //  MSoft fix2 for stuck title bar
      return TRUE;

   default:
      break;
   }
   return FALSE;
}

//**************************************************************************************
//  Restore the tray icon after Explorer restarts (crash, or manual restart).
//  When Explorer builds a new taskbar, the old tray icons are gone, and Explorer
//  broadcasts the registered message "TaskbarCreated" to every top-level window.
//  A program which does not respond to it keeps running with no icon.
//
//  Call this from the window procedure, for every message, before the main switch.
//  Returns TRUE if the message was TaskbarCreated (icon was added again),
//  FALSE for any other message.
//  Note: if the program ever runs elevated, the message must also be allowed through
//  UIPI, with ChangeWindowMessageFilterEx(hwnd, msg, MSGFLT_ALLOW, NULL).
//**************************************************************************************
BOOL respond_to_taskbar_created(UINT message)
{
   if (wm_taskbar_created == 0  ||  message != wm_taskbar_created) {
      return FALSE;
   }
   if (!Shell_NotifyIcon (NIM_ADD, &NotifyIconData)) {
      syslog(_T("tray icon restore failed: %s\n"), get_system_message()) ;
   }
   return TRUE;
}

// remove the icon from a system tray and free the .dll handle
void release_systray_resource(void)
{
   Shell_NotifyIcon (NIM_DELETE, &NotifyIconData);
}

